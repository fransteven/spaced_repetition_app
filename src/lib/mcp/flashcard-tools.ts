import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import type { CallToolResult } from '@modelcontextprotocol/sdk/types.js';
import { z } from 'zod';

import { CreateDeckSchema, CreateCardSchema, DbIdSchema } from '@/lib/validations';
import { ServiceError } from '@/lib/services/service-error';
import { createDeckForUser, listDecksForUser } from '@/lib/services/deck-service';
import { createCardsForUser, listCardsForDeck, updateCardForUser } from '@/lib/services/card-service';

/**
 * Deck and flashcard tools for the NeuroCards MCP server. Every write goes through the same
 * services as the UI, so ids are generated by the database and each new card gets its FSRS
 * schedule row. Nothing here accepts a card id for a new card or a user id.
 */

export const CARD_FORMAT_GUIDE = `How to write cards:
- One question or idea per card. Split long topics into several cards.
- "front" is only the question or cue, in plain words. No headings, numbering, emojis or labels like "FLASHCARD 1" or "Question:".
- "back" is the answer, short enough to recall (usually 1–4 sentences or a short list). Markdown is allowed.
- Put the topic in "tags" (e.g. ["aws", "ec2"]), not in the text.
- Before adding cards to an existing deck, call list_cards to avoid duplicates.`;

const MAX_CARDS_PER_CALL = 50;
const FRONT_PREVIEW = 160;

const TagsSchema = z
  .array(z.string().trim().min(1).max(40))
  .max(10)
  .describe('Topic tags, lowercase words');

const NewCardSchema = z.object({
  front: CreateCardSchema.shape.front.describe('The question or cue'),
  back: CreateCardSchema.shape.back.describe('The answer'),
  tags: TagsSchema.optional(),
});

function text(value: string): CallToolResult['content'][number] {
  return { type: 'text', text: value };
}

function failure(error: unknown, context: string, notFound: string): CallToolResult {
  if (error instanceof ServiceError) {
    // Ownership failures look like a missing resource: never confirm another user's ids.
    const message = error.code === 'FORBIDDEN' ? notFound : error.message;
    return { isError: true, content: [text(message)] };
  }
  console.error(context, error);
  return { isError: true, content: [text('Something went wrong on NeuroCards. Try again.')] };
}

function preview(value: string): string {
  const flat = value.replace(/\s+/g, ' ').trim();
  return flat.length > FRONT_PREVIEW ? `${flat.slice(0, FRONT_PREVIEW - 1)}…` : flat;
}

export function registerFlashcardTools(server: McpServer, userId: string, origin: string): void {
  const deckUrl = (id: string): string => `${origin}/decks/${id}`;

  server.registerTool(
    'list_decks',
    {
      title: 'List decks',
      description: "List the user's flashcard decks with their ids and card counts. Use it to pick the deck_id for create_cards.",
      inputSchema: {},
      annotations: { readOnlyHint: true, openWorldHint: false },
    },
    async () => {
      try {
        const decks = await listDecksForUser(userId);
        const items = decks.map((deck) => ({
          id: deck.id,
          name: deck.name,
          subject: deck.subject,
          total_cards: deck.total_cards,
          due_count: deck.due_count,
          url: deckUrl(deck.id),
        }));
        const summary =
          items.length === 0
            ? 'No decks yet. Create one with create_deck.'
            : items.map((d) => `- ${d.name} (${d.total_cards} cards, ${d.due_count} due) — id ${d.id}`).join('\n');
        return { content: [text(summary)], structuredContent: { decks: items } };
      } catch (error) {
        return failure(error, '[mcp list_decks]', 'Deck not found');
      }
    },
  );

  server.registerTool(
    'create_deck',
    {
      title: 'Create deck',
      description: 'Create a new flashcard deck. Prefer an existing deck from list_decks when one fits the topic.',
      inputSchema: {
        name: CreateDeckSchema.shape.name.describe('Deck name'),
        description: CreateDeckSchema.shape.description.describe('What the deck covers'),
        subject: CreateDeckSchema.shape.subject.optional().describe('Subject label, e.g. "English" or "Science". Defaults to "Custom".'),
      },
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
    },
    async ({ name, description, subject }) => {
      try {
        const deck = await createDeckForUser(userId, { name, description, subject: subject ?? 'Custom' });
        return {
          content: [text(`Created deck "${deck.name}" — id ${deck.id} — ${deckUrl(deck.id)}`)],
          structuredContent: { id: deck.id, name: deck.name, subject: deck.subject, url: deckUrl(deck.id) },
        };
      } catch (error) {
        return failure(error, '[mcp create_deck]', 'Deck not found');
      }
    },
  );

  server.registerTool(
    'list_cards',
    {
      title: 'List cards',
      description: 'List the cards of one deck (front preview, tags, study state). Optionally filter by words in the front, back or tags.',
      inputSchema: {
        deck_id: DbIdSchema.describe('Deck id (from list_decks)'),
        query: z.string().trim().max(100).optional().describe('Text to search in fronts, backs and tags'),
        limit: z.number().int().min(1).max(200).optional().describe('How many to return (default 50)'),
      },
      annotations: { readOnlyHint: true, openWorldHint: false },
    },
    async ({ deck_id, query, limit }) => {
      try {
        const all = await listCardsForDeck(userId, deck_id);
        const needle = query?.toLowerCase();
        const matching = needle
          ? all.filter((card) =>
              [card.front, card.back, ...(card.tags ?? [])].some((value) => value.toLowerCase().includes(needle)),
            )
          : all;
        const items = matching.slice(0, limit ?? 50).map((card) => ({
          id: card.id,
          front: preview(card.front),
          tags: card.tags ?? [],
          state: card.state ?? 'new',
        }));
        const header = `${matching.length} card(s)${needle ? ` matching "${query}"` : ''} in this deck${items.length < matching.length ? `, showing ${items.length}` : ''}.`;
        const lines = items.map((card) => `- ${card.front} [${card.state}] — id ${card.id}`);
        return {
          content: [text([header, ...lines].join('\n'))],
          structuredContent: { total: matching.length, cards: items },
        };
      } catch (error) {
        return failure(error, '[mcp list_cards]', 'Deck not found');
      }
    },
  );

  server.registerTool(
    'create_cards',
    {
      title: 'Create flashcards',
      description: `Add 1–${MAX_CARDS_PER_CALL} flashcards to one deck. NeuroCards assigns the ids and schedules each card as new for study.\n${CARD_FORMAT_GUIDE}`,
      inputSchema: {
        deck_id: DbIdSchema.describe('Deck id (from list_decks or create_deck)'),
        cards: z.array(NewCardSchema).min(1).max(MAX_CARDS_PER_CALL).describe('The cards to add'),
      },
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
    },
    async ({ deck_id, cards }) => {
      try {
        const created = await createCardsForUser(
          userId,
          deck_id,
          cards.map((card) => ({ front: card.front, back: card.back, tags: card.tags ?? [] })),
        );
        return {
          content: [text(`Added ${created.length} card(s). Study them: ${origin}/study/${deck_id}`)],
          structuredContent: {
            deck_id,
            created: created.map((card) => ({ id: card.id, front: preview(card.front) })),
            study_url: `${origin}/study/${deck_id}`,
          },
        };
      } catch (error) {
        return failure(error, '[mcp create_cards]', 'Deck not found');
      }
    },
  );

  server.registerTool(
    'update_card',
    {
      title: 'Update flashcard',
      description: `Fix the front, back or tags of an existing card (id from list_cards). Its study progress is kept.\n${CARD_FORMAT_GUIDE}`,
      inputSchema: {
        id: DbIdSchema.describe('Card id (from list_cards)'),
        front: CreateCardSchema.shape.front.optional().describe('New question or cue'),
        back: CreateCardSchema.shape.back.optional().describe('New answer'),
        tags: TagsSchema.optional().describe('New full list of tags (replaces the old one)'),
      },
      annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: true, openWorldHint: false },
    },
    async ({ id, front, back, tags }) => {
      if (front === undefined && back === undefined && tags === undefined) {
        return { isError: true, content: [text('Send a new front, back or tags.')] };
      }
      try {
        const card = await updateCardForUser(userId, id, { front, back, tags });
        return {
          content: [text(`Updated card: ${preview(card.front)}`)],
          structuredContent: { id: card.id, front: preview(card.front), tags: card.tags ?? [] },
        };
      } catch (error) {
        return failure(error, '[mcp update_card]', 'Card not found');
      }
    },
  );
}
