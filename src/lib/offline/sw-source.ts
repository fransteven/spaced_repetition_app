/**
 * Source of the hand-written service worker served at `/sw.js` (src/app/sw.js/route.ts).
 * Serwist needs webpack and this app builds with Turbopack, so the worker is a plain string.
 * Plan: docs/plans/offline-mode.md ("Service worker escrito a mano").
 *
 * - install: precaches the offline shells (/offline, /offline/read, /offline/study) and every
 *   `/_next/static/*` asset they reference (HTML → JS/CSS → chunks/fonts, bounded), into
 *   `nc-shell-<BUILD_ID>`.
 * - activate: drops other `nc-shell-*` caches. Content caches (`nc-images-v1`) are never touched.
 * - fetch: never handles /api/*, Server Actions or RSC requests. `/_next/static/*` is cache-first;
 *   navigations are network-first and fall back to the offline shells; images are served from
 *   `nc-images-v1` when present (filled by the deck download, never automatically).
 *
 * Written with String.raw so regex backslashes survive; the only interpolation is BUILD_ID.
 */

export const SHELL_CACHE_PREFIX = 'nc-shell-';
export const IMAGE_CACHE_NAME = 'nc-images-v1';
export const OFFLINE_SHELL_PAGES = ['/offline', '/offline/read', '/offline/study'] as const;

export function buildServiceWorkerSource(buildId: string): string {
  return String.raw`/* NeuroCards service worker — generated by src/lib/offline/sw-source.ts */
'use strict';

const BUILD_ID = ${JSON.stringify(buildId)};
const SHELL_PREFIX = ${JSON.stringify(SHELL_CACHE_PREFIX)};
const SHELL_CACHE = SHELL_PREFIX + BUILD_ID;
const IMAGE_CACHE = ${JSON.stringify(IMAGE_CACHE_NAME)};
const SHELL_PAGES = ${JSON.stringify(OFFLINE_SHELL_PAGES)};
const EXTRA_ASSETS = ['/icon.png', '/manifest.webmanifest'];
const MAX_ASSETS = 400;
const MAX_DEPTH = 3;

// "static/..." asset paths as they appear in HTML (/_next/static/...), in the RSC payload inlined in
// the HTML (escaped quotes) and in Turbopack chunks (relative to /_next/).
const STATIC_REF_RE = /static\/(?:chunks|css|media|[A-Za-z0-9_-]{6,})\/[A-Za-z0-9_\-.~%@\/\[\]]+?\.(?:js|css|woff2?|ttf|otf|png|jpe?g|gif|svg|webp|avif|ico|wasm)(?![A-Za-z0-9])/g;
const CSS_URL_RE = /url\(\s*(['"]?)([^'")]+)\1\s*\)/g;

function sameOrigin(url) {
  return url.origin === self.location.origin;
}

function isPrecachedPublicAsset(pathname) {
  return pathname.startsWith('/fonts/') || EXTRA_ASSETS.includes(pathname);
}

function extractRefs(text, baseUrl, isCss) {
  const out = new Set();
  for (const match of text.matchAll(STATIC_REF_RE)) {
    out.add('/_next/' + match[0]);
  }
  if (isCss) {
    for (const match of text.matchAll(CSS_URL_RE)) {
      const raw = match[2].trim();
      if (!raw || raw.startsWith('data:') || raw.startsWith('#')) continue;
      try {
        const url = new URL(raw, baseUrl);
        if (!sameOrigin(url)) continue;
        if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/fonts/')) {
          out.add(url.pathname);
        }
      } catch (e) {
        // ignore malformed url()
      }
    }
  }
  return out;
}

async function fetchFresh(path) {
  return fetch(new Request(path, { credentials: 'same-origin', cache: 'reload' }));
}

async function precacheShell() {
  const cache = await caches.open(SHELL_CACHE);
  const seen = new Set();
  let queue = [];

  // The shell pages are mandatory: if one fails the install fails and the browser retries later.
  for (const page of SHELL_PAGES) {
    const res = await fetchFresh(page);
    if (!res.ok || res.redirected) throw new Error('Shell ' + page + ' unavailable (' + res.status + ')');
    const html = await res.clone().text();
    await cache.put(page, res);
    for (const ref of extractRefs(html, self.location.origin + page, false)) queue.push(ref);
  }
  for (const asset of EXTRA_ASSETS) queue.push(asset);

  // Assets are best-effort: a missing chunk must not block the install. JS/CSS are scanned for
  // further chunk/font references (lazy chunks, next/font media), bounded by depth and count.
  for (let depth = 0; depth <= MAX_DEPTH && queue.length > 0; depth++) {
    const next = [];
    const batch = [...new Set(queue)].filter((p) => !seen.has(p)).slice(0, Math.max(0, MAX_ASSETS - seen.size));
    batch.forEach((p) => seen.add(p));
    await Promise.all(batch.map(async (path) => {
      try {
        const res = await fetchFresh(path);
        if (!res.ok || res.redirected) return;
        const isCss = path.endsWith('.css');
        if (path.endsWith('.js') || isCss) {
          const text = await res.clone().text();
          for (const ref of extractRefs(text, self.location.origin + path, isCss)) {
            if (!seen.has(ref)) next.push(ref);
          }
        }
        await cache.put(path, res);
      } catch (e) {
        // network hiccup on one asset: skip it, it will be cached on first use (cache-first on miss)
      }
    }));
    queue = next;
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(precacheShell());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((name) => name.startsWith(SHELL_PREFIX) && name !== SHELL_CACHE)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING' || (event.data && event.data.type === 'SKIP_WAITING')) {
    self.skipWaiting();
  }
});

function isRscOrAction(request, url) {
  const h = request.headers;
  return h.has('Next-Action') || h.has('RSC') || h.has('Next-Router-State-Tree') ||
    h.has('Next-Router-Prefetch') || url.searchParams.has('_rsc');
}

async function cacheFirstStatic(request) {
  const cache = await caches.open(SHELL_CACHE);
  const hit = await cache.match(request, { ignoreVary: true });
  if (hit) return hit;
  const any = await caches.match(request, { ignoreVary: true });
  if (any) return any;
  const res = await fetch(request);
  if (res.ok && res.type === 'basic') {
    cache.put(request, res.clone()).catch(() => {});
  }
  return res;
}

async function cacheFirstPublic(request) {
  const hit = await caches.match(request, { cacheName: SHELL_CACHE, ignoreVary: true, ignoreSearch: true });
  if (hit) return hit;
  return fetch(request);
}

async function shellPage(pathname) {
  const page = SHELL_PAGES.includes(pathname) ? pathname : '/offline';
  const hit = (await caches.match(page, { cacheName: SHELL_CACHE, ignoreSearch: true, ignoreVary: true })) ||
    (await caches.match(page, { ignoreSearch: true, ignoreVary: true }));
  return hit || new Response('You are offline.', {
    status: 503,
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
}

function safeDecode(segment) {
  try {
    return decodeURIComponent(segment);
  } catch (e) {
    return segment;
  }
}

function redirectTo(path) {
  return Response.redirect(new URL(path, self.location.origin).href, 302);
}

async function handleNavigation(request, url) {
  try {
    return await fetch(request);
  } catch (error) {
    const path = url.pathname.replace(/\/+$/, '') || '/';
    let m = path.match(/^\/read\/([^\/]+)$/);
    if (m) {
      const cfi = url.searchParams.get('cfi');
      return redirectTo('/offline/read?book=' + encodeURIComponent(safeDecode(m[1])) +
        (cfi ? '&cfi=' + encodeURIComponent(cfi) : ''));
    }
    m = path.match(/^\/study\/([^\/]+)$/);
    if (m) return redirectTo('/offline/study?deck=' + encodeURIComponent(safeDecode(m[1])));
    if (path === '/offline' || path.startsWith('/offline/')) return shellPage(path);
    return redirectTo('/offline');
  }
}

async function handleImage(request) {
  try {
    const cache = await caches.open(IMAGE_CACHE);
    const hit = await cache.match(request, { ignoreVary: true });
    if (hit) return hit;
  } catch (e) {
    // Cache Storage unavailable: fall through to the network
  }
  return fetch(request);
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') return;

  let url;
  try {
    url = new URL(request.url);
  } catch (e) {
    return;
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return; // blob:, data:, chrome-extension:

  if (request.destination === 'image') {
    if (sameOrigin(url) && url.pathname.startsWith('/api/')) return;
    event.respondWith(handleImage(request));
    return;
  }

  if (!sameOrigin(url)) return;
  if (url.pathname.startsWith('/api/') || url.pathname === '/sw.js') return;
  if (isRscOrAction(request, url)) return;

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigation(request, url));
    return;
  }
  if (url.pathname.startsWith('/_next/static/')) {
    event.respondWith(cacheFirstStatic(request));
    return;
  }
  if (isPrecachedPublicAsset(url.pathname)) {
    event.respondWith(cacheFirstPublic(request));
  }
});
`;
}
